-- Atomically reconcile the newcomer ledger and base totals from the client's computed minimum.
CREATE OR REPLACE FUNCTION public.apply_stage_newcomer_bonuses(
  p_stage_id uuid,
  p_bonuses jsonb DEFAULT '[]'::jsonb,
  p_source_minimum integer DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_changed integer := 0;
BEGIN
  IF NOT public.is_admin_user() THEN
    RAISE EXCEPTION 'administrator access required' USING ERRCODE = '42501';
  END IF;
  IF jsonb_typeof(COALESCE(p_bonuses,'[]'::jsonb)) <> 'array' THEN
    RAISE EXCEPTION 'bonus inputs must be a JSON array';
  END IF;
  PERFORM 1 FROM public.stages WHERE id=p_stage_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'stage not found'; END IF;
  IF EXISTS (SELECT 1 FROM public.sessions WHERE stage_id=p_stage_id AND committed IS DISTINCT FROM true) THEN
    RAISE EXCEPTION 'newcomer bonuses may only be reconciled after all stage sessions are committed';
  END IF;

  CREATE TEMP TABLE _newcomer_desired (player_id uuid PRIMARY KEY, points integer NOT NULL CHECK (points >= 0)) ON COMMIT DROP;
  INSERT INTO _newcomer_desired(player_id,points)
    SELECT (value->>'player_id')::uuid, (value->>'points')::integer
    FROM jsonb_array_elements(COALESCE(p_bonuses,'[]'::jsonb));

  WITH old_rows AS (
    SELECT player_id, points FROM public.stage_newcomer_bonuses WHERE stage_id=p_stage_id
  ), differences AS (
    SELECT COALESCE(n.player_id,o.player_id) AS player_id,
           COALESCE(n.points,0)-COALESCE(o.points,0) AS delta
    FROM old_rows o FULL JOIN _newcomer_desired n USING (player_id)
  )
  UPDATE public.players p SET base_pts=COALESCE(p.base_pts,0)+d.delta
    FROM differences d WHERE p.id=d.player_id AND d.delta<>0;
  GET DIAGNOSTICS v_changed = ROW_COUNT;

  DELETE FROM public.stage_newcomer_bonuses b
    WHERE b.stage_id=p_stage_id AND NOT EXISTS (SELECT 1 FROM _newcomer_desired n WHERE n.player_id=b.player_id);
  INSERT INTO public.stage_newcomer_bonuses(stage_id,player_id,points,source_minimum,updated_at)
    SELECT p_stage_id,player_id,points,COALESCE(p_source_minimum,0),now() FROM _newcomer_desired
    ON CONFLICT (stage_id,player_id) DO UPDATE SET points=EXCLUDED.points,
      source_minimum=EXCLUDED.source_minimum,updated_at=now();
  INSERT INTO public.score_recalculation_audit(stage_id,session_id,actor,status,details)
    VALUES (p_stage_id,NULL,auth.uid(),'completed',jsonb_build_object('kind','newcomer_bonus_reconciliation','updated_players',v_changed,'minimum',p_source_minimum,'bonuses',p_bonuses));
  RETURN jsonb_build_object('stage_id',p_stage_id,'updated_players',v_changed,'minimum',p_source_minimum);
END;
$$;
REVOKE ALL ON FUNCTION public.apply_stage_newcomer_bonuses(uuid,jsonb,integer) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.apply_stage_newcomer_bonuses(uuid,jsonb,integer) TO authenticated;
