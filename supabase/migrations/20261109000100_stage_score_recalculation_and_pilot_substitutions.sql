CREATE OR REPLACE FUNCTION public.apply_player_score_adjustment(p_player_id uuid, p_target_total integer, p_note text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_old integer; v_delta integer;
BEGIN
  IF NOT public.is_admin_user() THEN RAISE EXCEPTION 'administrator access required' USING ERRCODE='42501'; END IF;
  SELECT COALESCE(base_pts,0) INTO v_old FROM public.players WHERE id=p_player_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'player not found'; END IF;
  v_delta := p_target_total-v_old;
  IF v_delta <> 0 THEN
    UPDATE public.players SET base_pts=p_target_total WHERE id=p_player_id;
    INSERT INTO public.score_manual_adjustments(player_id,delta,previous_total,new_total,note,actor)
      VALUES(p_player_id,v_delta,v_old,p_target_total,NULLIF(BTRIM(p_note),''),auth.uid());
  END IF;
  RETURN jsonb_build_object('player_id',p_player_id,'previous_total',v_old,'new_total',p_target_total,'delta',v_delta);
END $$;
REVOKE ALL ON FUNCTION public.apply_player_score_adjustment(uuid,integer,text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.apply_player_score_adjustment(uuid,integer,text) TO authenticated;

